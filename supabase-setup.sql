-- Run this in Supabase SQL Editor.
create table if not exists public.site_settings (
  id integer primary key default 1 check (id = 1),
  brand text not null default 'Galleria',
  tagline text,
  about_en text,
  about_ar text,
  email text,
  phone text,
  instagram text
);
insert into public.site_settings (id, brand) values (1, 'Galleria') on conflict (id) do nothing;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name_en text not null,
  name_ar text,
  description_en text,
  description_ar text,
  category text not null check (category in ('Tote Bag','Stickers','Mug','Keychain')),
  image_url text not null,
  published boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.site_settings enable row level security;
alter table public.products enable row level security;

-- Admin allow-list: insert your authenticated user's UUID here after creating the user.
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.admin_users enable row level security;

create or replace function public.is_galleria_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.admin_users where user_id = auth.uid()); $$;

create policy "Public can read site settings" on public.site_settings
for select using (true);
create policy "Admins manage site settings" on public.site_settings
for all using (public.is_galleria_admin()) with check (public.is_galleria_admin());

create policy "Public can read published products" on public.products
for select using (published = true or public.is_galleria_admin());
create policy "Admins manage products" on public.products
for all using (public.is_galleria_admin()) with check (public.is_galleria_admin());

-- Create a PUBLIC Storage bucket named product-images in Storage.
-- These policies allow public viewing and admin uploads/deletes.
create policy "Public can view product images" on storage.objects
for select using (bucket_id = 'product-images');
create policy "Admins can upload product images" on storage.objects
for insert to authenticated with check (bucket_id = 'product-images' and public.is_galleria_admin());
create policy "Admins can update product images" on storage.objects
for update to authenticated using (bucket_id = 'product-images' and public.is_galleria_admin()) with check (bucket_id = 'product-images' and public.is_galleria_admin());
create policy "Admins can delete product images" on storage.objects
for delete to authenticated using (bucket_id = 'product-images' and public.is_galleria_admin());
